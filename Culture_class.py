import numpy as np
from scipy.stats import percentileofscore
from Larva_class import Larva

class Culture:
    def __init__(self, Surface_area = 400, Height = 15, Diffuse = False, 
                 W_band = 0.01, Nut_per_uL = 160, Saturate  = 0.04):
        '''
        Creates an instance of a larval culture with given parameters. 
        Multiple instances of class Larva populate the culture. 
        Each 'larva' has trait values generated by the TraitGen function.
        
        The __init__ constructor sets up parameters of the culture itself. 
        Eggs are added in 'Add_eggs' function.
        
        The culture is assumed to be in a cylindrical vial.
        Surface area (cross section) and Height of food column are used 
        to calculate the mass of Food present in the starting culture. 
        
        Parameters
        ----------
        Surface_area : float
            Cross section surface area of cylindrical vial. 
            The default is 400 mm2.
            
        Height : float
            Depth of food column. 
            The default is 15 mm.
        
        Diffuse : bool
            Implement waste diffusion across food column if True.
            The default is False: NO diffusion of waste across food column.
            
            True: The waste saturates each 'layer' of food before going down
            food column to the next layer. The Saturate property determines the
            waste concentration required for saturation at each food layer.
            
        W_band : float
            depth of band of food into which diffused waste spreads uniformly.
            Also called food layer.
            The default is 0.01 mm.
            
        Saturate: float
            Waste concentration at which the food layer saturates with waste,
            and the waste has to go down the food column.
            The default is 4%.
            
        Nut_per_uL : float
            Defines the nutrient density: ug nutrients per micro litre of food.
            The default is 160 ug/uL; based on cornmeal medium used.
            See Sarangi et al. 2016 for full recipe. 

        Returns
        -------
        None.

        '''
        # Sets cross section surface area and height (depth) of food column
        self.SA_food = Surface_area # square mm
        self.Height_food = Height # mm
        
        # SA_food and Height_food are used to calculate Food volume,
        # A cylindrical food column is assumed
        
        Vol_food = self.Height_food * self.SA_food # cubic mm or uL
        
        # Nutrient density (ug/uL)
        self.Nut_per_uL = Nut_per_uL
        # Food mass is calculated based on the dry mass of nutrients added
        self.Food_mass = Vol_food * self.Nut_per_uL
        
        # Initiate realised food mass with calculated food mass
        self.Food_current = self.Food_mass
        
        self.Diffuse_status = Diffuse # True if diffusion is implemented
        
        self.WB_height = W_band # depth of a single band of diffused waste
        
        # Number of waste bands that can be formed, given food column height
        self.WB_num = int(np.ceil(self.Height_food/self.WB_height))
        
        self.Larvae = [] # Container for larval instances
        
        # Sets the saturation limit (ug waste) per food layer
        # by % (Saturate) of Waste/(Waste + Food in layer)
        self.Sat_W = (self.Food_mass/self.WB_num) * (Saturate/(1 - Saturate))
        
        return None
    
        # End of Culture constructor #########################################
    
    def Add_eggs(self, Eggnum, Trait_array, calibrated_min_crit = 180,
                 Post_crit_lim = 36, Waste_conversion = 0.025,
                 BS_initial = 0.00007, BS_final_ratio = 0.5):
        '''
        Populates the culture instance with eggs of given number.
        This function is kept separate to add modularity to addition of eggs,
        and allow easy inclusion of bitypic and other complex cultures.
        
        For implementing competition between two or more types, 
        change ID number in the input Trait_array.
        
        For implementation of head start in competition, change the 
        mean hatch time of a group by the amount of head start/disadvantage.

        Parameters
        ----------
        Eggnum : int
            Number of eggs added to the culture.
        Trait_array : ndarray
            2D array of trait values for each larva.
            See TraitGen function (Traits.py) for description.

        Returns
        -------
        None.

        '''
        
        for i in range(Eggnum):
            # Adds a larval instance with respective trait value for each i
            self.Larvae.append(Larva(Trait_array[:, i], calibrated_min_crit,
                                     Post_crit_lim, Waste_conversion,
                                     BS_initial, BS_final_ratio))
        
        return None
    
    ##### End of Add_eggs function ###########################################
    
    
    def SatDiff(self, T):
        '''
        This defines the saturation based diffusion of metabolic waste into the
        food column. As the waste is excreted on the top food layer, it begins
        to saturate the top food layer up to the saturation limit. As more 
        waste gets added to the food, the top layers get saturated, and the 
        waste starts saturating the subsequent layer, down from the top layer.
        If all layers are saturated, the waste accumulates on the top 
        (i.e., the top layer gets additional waste).
        
        NOTE: As the food gets consumed, the total number of food layers get 
        depleted. As a consequence, the entire stack of remaining food layers 
        gets moved down equal to the number of layers depleted.

        Parameters
        ----------
        T : int
            Current time step.

        Returns
        -------
        None.

        '''
        
        # if T == 90:
        #     barr = 0
        
        # Current food column height is calculated
        Current_height = (self.Food_current/self.Nut_per_uL)/self.SA_food
        # Number of waste bands possible currently
        # WBnc: Waste Band number current
        WBnc = int(np.ceil(Current_height/self.WB_height))
        
        # Number of deactivated layers due to diminishing food volume
        self.Dctlyrs[T] = self.WB_num - WBnc
        
        if self.Dctlyrs[T] > 0:
            # if deactivated layers are greater than 0
            for d in range(self.Dctlyrs[T]):
                # iterating over all deactivated layers in WB_profile
                if (self.WB_profile[T-1, d] == 0 or 
                    self.WB_profile[T-1, d] == -1):
                    # if there is NO waste present in current deactivated 
                    # layer, set its value to -1
                    self.WB_profile[T, d] = -1
                    self.WB_status[T, d] = -1
                
                elif self.WB_profile[T-1, d] > 0:
                    # if there IS waste present in current deactivated layer,
                    # shift the waste to the first active layer (from top)
                    self.WB_profile[T, -1] += self.WB_profile[T-1, d]
                    # set the current deactivated layer's value to -1
                    self.WB_profile[T, d] = -1
                    # status of deactivated food layer is also set to -1
                    self.WB_status[T, d] = -1
        
        # Find the time point from which waste is excreted at the current t
        W_excr_T = np.where(self.Waste_new[:, 3] == 0)
        # For debugging, ensures that there is only 1 or no value for 
        # time point of fresh waste excreted
        assert 0 <= len(W_excr_T[0]) <= 1
        
        # Waste to be deposited, placeholder = 0.
        Wdep = 0
        
        if len(W_excr_T[0]) == 1:
            # If there IS a time point found from which waste will be excreted
            # Set W_excr_T as the waste time point
            W_excr_T = W_excr_T[0][0]
            # Calculates the waste excreted at the given W_excr_T time point
            Wdep = self.Waste_new[W_excr_T, 0]
            
        if np.all(self.WB_status[T-1, self.WB_status[T-1, :] != -1] == 1):
            # If all active layers are saturated with waste
            # the waste is deposited at the top food layer
            self.WB_profile[T, -1] += Wdep
            # Waste status of food layer updated
            self.WB_status[T, -1] = 1
            # waste to be deposited is depleted (set to 0 ug.)
            Wdep = 0
        
        for w in range((self.WB_num-1), -1, -1):
            # starting from the top layer and iterating downwards to bottom
            if self.WB_status[T-1, w] == 1 and self.WB_status[T, w] != -1:
                # If previous time step food layer is saturated AND 
                # current time step food layer is not deactivated
                if w == (self.WB_num - 1):
                    # If current layer is top layer
                    # Set current time step top layer status as saturated
                    self.WB_status[T, w] = 1
                    # Add previous time step's top layer waste to current one
                    self.WB_profile[T, w] += self.WB_profile[T-1, w]
                    
                else:
                    # If food layer is saturated, but w is not top layer,
                    # current food layer status set as saturated.
                    self.WB_status[T, w] = 1
                    
                    # debug
                    # if w < (self.WB_num-1):
                    #     if self.WB_status[T, w+1] == 0:
                    #         foo = 55
                            
                    assert self.WB_status[T, w+1] != 0
                    
                    # waste amount in layer w is copied from previous time step
                    self.WB_profile[T, w] = self.WB_profile[T-1, w]
                
            elif 0 <= self.WB_status[T-1, w] <1 and self.WB_status[T, w] != -1:
                # If previous food layer is unsaturated 
                # and current food layer is undepleted (!= -1))
                if Wdep > 0:
                    # If waste to be deposited is greater than 0 ug
                    # Calculate remaining waste amount that can be 
                    # accomodated in current layer
                    Rem_waste = (1 - self.WB_status[T-1, w]) * self.Sat_W
                    
                    if Wdep >= Rem_waste:
                        # If waste to be deposited exceeds remaining waste
                        # that can fit in current layer
                        # Current food layer at current time step is updated as
                        # current food layer prev. time step +
                        # remaining waste amount
                        self.WB_profile[T, w] = (self.WB_profile[T-1, w] + 
                                                 Rem_waste)
                        # Set food layer status as proportion of sat. limit.
                        # since Wdep > Rem_waste, this should be 1
                        self.WB_status[T, w] = (self.WB_profile[T, w]/
                                                self.Sat_W)
                        
                        # debug
                        # if np.round(self.WB_status[T, w], 4) != 1:
                        #     boo = "far"
                        # this checks if the abovementioned condition is true.
                        assert np.round(self.WB_status[T, w], 4) == 1
                        
                        self.WB_status[T,w] = np.round(self.WB_status[T,w],4)
                        # waste deposited is subtracted by the remaining waste.
                        Wdep -= Rem_waste
                        
                    elif Wdep < Rem_waste:
                        # if waste to be deposited is less than remaining 
                        # waste saturation potential of current food layer
                        # current food layer at current time step =
                        # current layer at prev. time step + waste deposited
                        self.WB_profile[T, w] = (self.WB_profile[T-1, w] + 
                                                 Wdep)
                        
                        # the status of current food layer at t is set as
                        # the saturation level of the current layer
                        # this should be less than 1
                        self.WB_status[T, w] = (self.WB_profile[T, w]/
                                                self.Sat_W)
                        # abovementioned condition is tested
                        assert 0 < self.WB_status[T, w] < 1
                        # waste to be deposited is depleted, thus set to 0.
                        Wdep = 0
                        
                elif Wdep == 0:
                    # If there is no waste to be deposited
                    # the waste from the previous time step is carried over to 
                    # the current time step in the current layer w
                    self.WB_profile[T, w] = self.WB_profile[T-1, w]
                    # waste status is also carried over
                    self.WB_status[T, w] = self.WB_status[T-1, w]
            
        # print(T, ", ", W_excr_T) # debug
        
        # roll all deactivated layers at previous time step to the top
        # This helps in better visualisation of depleting food
        self.WB_profile[T-1, :] = np.roll(self.WB_profile[T-1, :],
                                          -self.Dctlyrs[T-1])
        # similarly, roll the status records of food layers at T-1
        self.WB_status[T-1, :] = np.roll(self.WB_status[T-1, :],
                                          -self.Dctlyrs[T-1])
        
        return None
        
    def Digging(self, Time, index):
        '''
        Implements variable larval food access through varying digging depths.
        
        NOTE: Waste bands and food layers are used interchangeably, depending
        on suitability of terminology.
        
        Parameters
        ----------
        index : int
            Index of the larva in the Larvae array.
        Time : int
            Current time step.

        Returns
        -------
        Food_exp : Food accessed by the larva
        Waste_exp : Waste experienced by the larva
        Bands_available : Number of waste diffusion bands accessed by the larva
        Dig_upper_limit : deepest layer accessible by larva
        Dig_lower_limit : shallowest layer accessible by larva

        '''
        t = Time
        i = index
        
        # Calculate digging length by ith larva at time step t
        self.DigLen_profile[t, i] = (self.Larvae[i].Larval_length *
                                     self.Larvae[i].Digging_factor)
        
        # Deepest layer accessible by larva
        Dig_upper_limit = int(np.ceil(self.DigLen_profile[t, i]/
                                      self.WB_height))
        # Shallowest layer accessible by larva
        Dig_lower_limit = int(np.floor(self.Larvae[i].Larval_length/
                                       self.WB_height))
        
        # The number of waste bands that the larva experiences
        # This is used to calculate the total food and total waste that the 
        # larva experiences at time step t
        Bands_available = Dig_upper_limit - Dig_lower_limit
        
        assert Bands_available >= 1
        
        # Waste band list at time t
        Bands_list = self.WB_profile[t,self.WB_profile[t, :] > -1]
        
        # Number of waste bands possible currently
        Bands_len = len(Bands_list)
        
        ### NOTE: Waste_new updates the waste level per larva at time t,
        # thus, it is not used for the within-time step waste experienced.
        
        # debug
        # if (Dig_lower_limit + 1) >= Bands_len:
        #     barr = 0
        
        if Dig_upper_limit > Bands_len:
            # If the total digging length exceeds the total number of bands,
            # then food accessed is the total food
            Food_exp = self.Food_current
            # The waste experienced is the total waste
            Waste_exp = np.sum(Bands_list)
            
        else:
            # If total digging length is <= total number of bands
            # Food experienced by larva is a fraction defined by 
            # its available bands number divided by the total bands number
            Food_exp = self.Food_current * (Bands_available/Bands_len)
            # Waste experienced placeholder
            Waste_exp = 0
            
            for e in range((Bands_len - Dig_upper_limit), 
                           (Bands_len - Dig_lower_limit)):
                # Starting from the deepest waste band, loop to the 
                # uppermost waste band available to the larva
                # Add waste from the eth band to the waste experienced 
                # by the larva
                Waste_exp += Bands_list[e]
            
            # print("t=", t, "i=", i, "Bands=", Bands_available, "Waste=", np.round(Waste_exp, 2), "Food=", np.round(Food_exp, 2), "W conc=", np.round(Waste_exp/(Food_exp + Waste_exp), 8))
           
        return Food_exp, Waste_exp, Bands_available, Dig_upper_limit, Dig_lower_limit
    
    ############### End of Digging function ##################################

    def Culture_run(self, Time, Conditions = [0, 0], 
                    StartSA = 0.1, GrowSA = 0.01, Excrete_timer = 3):
        '''
        Runs the instance of Culture with given time steps and 
        given conditions. 
        Requires eggs to be added (eg. via Add_eggs) before commencement.
        
        NOTES: 
            1. All mass mentioned in the following code refers to dry mass.
            2. SA : Surface Area (cross-section)

        Parameters
        ----------
        Time : int
            Number of time steps over which Culture instance will run.
        
        Conditions : list
            Determines the processes that act in the running of culture. 
            Each index has different properties and values:
                
                Conditions[0]: surface area availability changes feeding rate
                = 0: No effect of surface area availability 
                (availability not calculated).
                (>= 1: surface area availabilty calculated using two variables:
                 StartSA and GrowSA (see below). 
                 
                = 1: For each larva, Bite rate increases as a function of 
                SA occupancy, the point of increase is dependent on the
                inflection point.
                There is also a max. plastic bite rate achievable 
                (see Traits function and Larva_class for details)
                Additionally,
                The food eaten volume decreases as a function of SA occupancy,
                as well as the percentile of a larva's relative mass.
                
                
                Conditions[1]: Waste ingestion conditions
                = 0: No effect of ingested waste
                >= 1: Larva dies if ingested waste crosses tolerance threshold.
                    No effect on bite rate.
                
                = 2: Bite rate reduces due to ingested waste. 
                    The reduction in bite rate has a NON linear relationship 
                    with Waste ingested/Waste threshold.
                    Larva dies if ingested waste crosses tolerance threshold
                
            The default is [0, 0].
            
        StartSA : float (range 0 to 1)
            Starting surface area effectively available for feeding. 
            If Conditions[0] >= 1; 
                StartSA is a fraction of vial SA.
                This determines the starting available SA for feeding.
            The default is 2%.
            
        GrowSA : float
            If Conditions[0] >= 1; 
                GrowSA is the fraction of vial SA by which effectively 
                available SA grows every time step.
                
            The default is 1%.
                
        Excrete_timer : int
            Time steps after which food eaten by larva is converted to waste
            and excreted by larvae. 
            For bookkeeping purposes, waste is converted instantly, but is 
            added to the system through a timer present in the Waste_new array.
            
            The default is 1 hour.
            
        Returns
        -------
        None.

        '''
        # Ensure that eggs have been added to culture before commencement
        if self.Larvae == []:
            raise Exception("Add_eggs first!")
            
        assert 0 < StartSA < 1, "Starting fraction of available SA should be between 0 and 1!!!"
        
        assert Excrete_timer >= 0, "Excrete timer cannot be negative!!!"
        
        # Count of larvae, for indexing purposes
        Larval_count = len(self.Larvae)
        
        # Profile to map larval mass over time, for each larva
        self.Mass_profile = np.zeros((Time, Larval_count))
        # Profile to map larval cross section SA over time, for each larva
        self.SA_profile = np.zeros((Time, Larval_count))
        # Profile to map larval length over time, for each larva
        self.Length_profile = np.zeros((Time, Larval_count))
        # Profile to map larval status over time, for each larva
        # See Larva_class for details of status
        self.Status_profile = np.zeros((Time, Larval_count))
        # Profile to map larval mass percentile per larva for each time step
        self.Mass_percentile = np.zeros((Time, Larval_count))
        # Records each of the following per larva, in the given order:
        # Egg mass; Min. crit. mass; Mass achieved, Max. mass possible;
        # Time of post crit.; Status achieved.
        self.Mass_records = np.zeros((7, Larval_count))
        
        # Hatching time records - the hatch counter decreases over time.
        self.Hatch_counter = np.zeros((Time, Larval_count))
        # Post critical mass feeding counter
        self.Post_crit_counter = np.zeros((Time, Larval_count))
        
        # Profile to map total food quantity across time
        self.Food_profile = np.zeros(Time)
        # First time step of Food_profile is initial food
        self.Food_profile[0] = self.Food_current
        
        # Realised waste level in culture
        Waste_current = 0
        # Profile to map total waste quantity across time
        self.Waste_profile = np.zeros(Time)
        # First time step of Waste_profile is current waste
        self.Waste_profile[0] = Waste_current
        
        # Total waste generated per time step
        # Index 0 maps new waste
        # Index 1 maps diffusion timer (defunct!)
        # Index 2 maps waste band position
        # Index 3 maps waste excretion timer
        self.Waste_new = np.zeros((Time, 4))
        # Add placeholder value to excretion timer
        self.Waste_new[:, 3] = -1
        
        # Profile to map waste generated over time
        self.Waste_gen = np.zeros((Time, Larval_count))
        
        # Profile to map waste diffusion over time
        # Contains columns for waste diffusion bands
        # The total column number is the max possible diffusion bands
        self.WB_profile = np.zeros((Time, self.WB_num))
        # For saturation based diffusion, tracks the saturation status of 
        # each food layer
        # 0-1: Saturation limit; -1: deactivated layer
        self.WB_status = np.zeros((Time, self.WB_num))
        
        # Tracks number of deactivated food layers
        self.Dctlyrs = np.zeros(Time, dtype = int)
        
        # Lots of larval feeding recorders, mostly for diagnostics
        # Profile to map efficiency over time
        self.Efficiency_profile = np.zeros((Time, Larval_count))
        # Profile to map larval growth over time
        self.Growth_profile = np.zeros((Time, Larval_count))
        # Profile to map realised bite rate over time
        self.BR_profile = np.zeros((Time, Larval_count))
        # Profile to map uncrowded bite rate over time
        self.BR_uncrowded_prof = np.zeros((Time, Larval_count))
        # Profile to map waste modifier on bite rate over time
        self.BR_waste_mod_prof = np.zeros((Time, Larval_count))
        # Profile to map SA occupancy modifier on bite rate over time
        self.BR_SA_mod_prof = np.zeros((Time, Larval_count))
        # Profile to map realised bite scale over time
        self.BS_profile = np.zeros((Time, Larval_count))
        # Profile to map bite mass over time
        self.BM_profile = np.zeros((Time, Larval_count))
        # Profile to map food eaten over time
        self.FE_profile = np.zeros((Time, Larval_count))
        # Profile to map waste ingested over time
        self.WI_profile = np.zeros((Time, Larval_count))
        # Profile to map waste tolerance threshold over time
        self.WT_profile = np.zeros((Time, Larval_count))
        
        # Records Digging length per larva per time step
        self.DigLen_profile = np.zeros((Time, Larval_count))
        # Records upper bound of waste bands depth access
        self.Dig_upper = np.zeros((Time, Larval_count))
        # Records lower bound of waste bands depth access
        self.Dig_lower = np.zeros((Time, Larval_count))
        # Records number of bands accessed per larva per time step
        self.Access_profile = np.zeros((Time, Larval_count))
        # Records waste experienced per larva per time step
        self.W_exp_profile = np.zeros((Time, Larval_count))
        # Records waste concentration experienced per larva per time step
        self.W_conc_profile = np.zeros((Time, Larval_count))
        # Records food experienced per larva per time step
        self.F_exp_profile = np.zeros((Time, Larval_count))
        # Records food concentration experienced per larva per time step
        self.F_conc_profile = np.zeros((Time, Larval_count))
        
        # Records the feeding band density per larva per time step
        self.Dens_exp = np.zeros(Time)
        # Records the available surface area for feeding across time
        self.SA_available = np.zeros(Time)
        # Sets the starting surface area available as a % of total food SA
        self.SA_available[0] = StartSA * self.SA_food
        # Records total larval cross section surface area across time
        self.L_SA_total = np.zeros(Time)
        # Records reduction in food eaten due to high SA occupancy
        self.ReduceFEmod = np.zeros((Time, Larval_count))
        # Records mass based food eaten reduction due to high SA occupancy
        self.RedMass = np.zeros((Time, Larval_count))
        
        for x in range(Larval_count):
            # Sets starting values (time step t = 0) for 
            # larval mass, SA, Length, Status, HT_counter
            self.Mass_profile[0, x] = self.Larvae[x].Egg_mass
            self.SA_profile[0, x] = self.Larvae[x].Egg_SA
            self.Length_profile[0, x] = self.Larvae[x].Egg_length
            self.Status_profile[0, x] = self.Larvae[x].Status
            self.Hatch_counter[0, x] = self.Larvae[x].HT_counter
        
        # Container to record time to wandering
        self.Dev_time = np.zeros(Larval_count)
        # Container to record time of larval death
        self.Mort_time = np.zeros(Larval_count)
        
        # Indices are shuffled at the beggining of each time step.
        # Create index array
        Indices = np.arange(Larval_count)
        # Profile to map order of indices at each time step
        self.Indices_profile = np.zeros((Time, Larval_count))
        # Time step (t) = 0 all indices are in ascending order
        self.Indices_profile[0, :] = Indices
        # Loads random number generator for randomly shuffling indices
        rng = np.random.default_rng()
        
        for t in range(1, Time):
            # Iterates over all time steps t=1 to (Time-1)
            
            if self.Diffuse_status == True:
                # Implements waste diffusion based on waste saturation limit.
                self.SatDiff(t)
                
            if Conditions[0] >=1:
                # Space limitation exists in the form of limited surface area
                # available for feeding. See Culture_run doc. for details.
                
                if self.SA_available[t-1] < (self.SA_food * 0.95):
                    # If there is still vial SA available to be exploited in
                    # the vial, the expansion of effectively available SA is in
                    # part due to the GrowSA (independent of larval SA)
                    
                    self.SA_available[t] = (self.SA_available[t-1] +
                                               (self.SA_food * GrowSA))
                    
                    if (
                        (
                        (np.any(self.Status_profile[t-1, :] == 1)) 
                        or
                        (np.any(self.Status_profile[t-1, :] == 2))
                        )
                        and
                        (self.SA_available[t-1] < self.L_SA_total[t - 1])
                        ):
                        # If total larval SA exceeds effecitvely available SA.
                        # assuming there are still some larvae feeding.
                        # The available cross section surface area expands by 
                        # given fraction of current available surface area
                        # The expansion is in part due to larval SA at t-2
                        
                        self.SA_available[t] += (self.L_SA_total[t-1] -
                                                 self.SA_available[t-1])/10
                    
                else:
                    # The surface area available remains unchanged
                    self.SA_available[t] = self.SA_available[t-1]
                
                # if np.any(self.Status_profile[t-1, :] == 3):
                #     # debug purposes
                #     foo = 1
                
                # Marks all the larvae still feeding 
                Statcheck = ((self.Status_profile[t-1,:]==1)|
                             (self.Status_profile[t-1,:]==2))
                
                # Calculates total cross-section surface area 
                # of all feeding larvae
                self.L_SA_total[t] = np.sum(self.SA_profile[t - 1, Statcheck])
                #Calculates updated larval occupancy of surface area available
                self.Dens_exp[t] = self.L_SA_total[t]/self.SA_available[t]
            
            
            # Randomly shuffle all larval indices
            Indices = rng.permutation(Larval_count)
            # Store shuffled indices at t
            self.Indices_profile[t, :] = Indices
            
            # Check to see that all indices are present post shuffling
            tempuniq, tempcount = np.unique(Indices, return_counts=True)
            assert np.all(tempcount==1)
            
            for i in Indices:
                # Iterates over shuffled Indices
                
                # Calculates the percentile score for body mass of ith larva
                # at time t, stored in mass_percentile profile
                self.Mass_percentile[t, i] = percentileofscore(
                    self.Mass_profile[t-1, :], self.Mass_profile[t-1, i]
                    , 'mean')
                
                if self.Larvae[i].Status==0:
                    # ith egg is unhatched
                    # At every t, every egg counts down -1 t towards hatching
                    self.Larvae[i].HT_counter -= 1
                    # Recorded in Hatch_counter for ith larva at t
                    self.Hatch_counter[t, i] = self.Larvae[i].HT_counter
                    # if t > 50, it should usually be indicative of error.
                    # this assertion should be inaccessible after hatching
                    assert len(self.Hatch_counter[0:t, i]) <= 50
                    
                    if self.Larvae[i].HT_counter==0:
                        # Hatch counter for ith larva has run out
                        # Larva hatches out of egg, status 'PreCrit' i.e. 1
                        self.Larvae[i].Status = 1
                
                elif (0<self.Larvae[i].Status<3):
                    # ith larva has hatched and is not dead or wandering
                    # (it's still feeding)
                    if self.Food_current<=500:
                        # Food is below a minimum amount, this value is kept
                        # >0 to prevent negative food values
                        if self.Larvae[i].Status!=2:
                            # ith larva is not in post critical mass stage
                            # it dies of starvation
                            # Its status is set to 'starved' i.e. -1
                            self.Larvae[i].Status = -1
                            # Its mass, SA and length are set to 0
                            self.Larvae[i].Mass = 0
                            self.Larvae[i].Larval_SA = 0
                            self.Larvae[i].Larval_length = 0
                            # The time of larval death is recorded
                            self.Mort_time[i] = t
                            
                        elif self.Larvae[i].Status==2:
                            # ith larva is in post critical mass stage
                            # it commits to wandering i.e. Status = 3
                            self.Larvae[i].Status = 3
                            # The time to wandering is recorded
                            self.Dev_time[i] = t
                            
                    else:
                        # Sufficient food is present
                            
                        # Set up diffusion bands no. accessed for Diffusion
                        # Placeholder at 0 (also for no Diffusion case)
                        Bands = 0
                        
                        if self.Diffuse_status == True:
                            # If Diffusion of waste occurs,
                            # Then digging also occures.
                            # Call digging function and update
                            # the food available and waste experienced
                            Food_exp, Waste_exp, Bands, self.Dig_upper[t, i], self.Dig_lower[t, i] = self.Digging(t, i)
                            
                        else:
                            # In the absence of waste, total food and 
                            # total waste are experienced
                            Food_exp = self.Food_current
                            Waste_exp = Waste_current
                        
                        
                        #######################################################
                        ########## Initiate larval feed function ##############
                        #######################################################
                        
                        # See Larva_class Feed function for details
                        self.Waste_gen[t, i], self.ReduceFEmod[t, i], self.BR_uncrowded_prof[t, i], self.BR_waste_mod_prof[t, i], self.BR_SA_mod_prof[t, i], self.RedMass[t, i] = self.Larvae[i].Feed(
                            Food = Food_exp, Waste = Waste_exp, 
                            Dens_exp = self.Dens_exp[t], Con0 = Conditions[0],
                            Con1 = Conditions[1], 
                            Masspercentile = self.Mass_percentile[t, i]
                            )
                        
                        # Food reduced by food eaten
                        self.Food_current -= self.Larvae[i].Food_eaten
                        # Waste eaten is pre-reduced from 
                        # new Waste generated
                        
                        # Record larval parameters for diagnostics
                        
                        # Realised efficiency
                        self.Efficiency_profile[t, i] = (
                            self.Larvae[i].Efficiency_current)
                        # Larval growth
                        self.Growth_profile[t, i] = (
                            self.Larvae[i].Growth)
                        # Realised bite rate
                        self.BR_profile[t, i] = (
                            self.Larvae[i].BR_current)
                        # Realised bite scale
                        self.BS_profile[t, i] = (
                            self.Larvae[i].BS_current)
                        # Bite mass profile
                        self.BM_profile[t, i] = (
                            self.Larvae[i].Bite_mass)
                        # Food eaten profile updated
                        self.FE_profile[t, i] = (
                            self.Larvae[i].Food_eaten)
                        
                        # Record waste experienced
                        self.W_exp_profile[t, i] = Waste_exp
                        # Record waste concentration experienced
                        self.W_conc_profile[t, i] = (
                            Waste_exp/(Food_exp + Waste_exp))
                        # Record number of food bands accessed
                        self.Access_profile[t, i] = Bands
                        # Record food experienced
                        self.F_exp_profile[t, i] = Food_exp
                        # Record food concentration experienced
                        self.F_conc_profile[t, i] = (
                            Food_exp/(Food_exp + Waste_exp))
                        
                        # Waste generated by larva added to fresh waste
                        self.Waste_new[t, 0] += self.Waste_gen[t, i]
                        # Waste excretion timer added to new waste
                        self.Waste_new[t, 3] = Excrete_timer
                        # Waste ingested profile updated
                        self.WI_profile[t, i] = (
                            self.Larvae[i].Waste_ingested_total)
                        # Waste tolerance threshold, scales with mass
                        self.WT_profile[t, i] = (
                            self.Larvae[i].Waste_threshold)
                        
                        
                        if (
                            Conditions[1]>0 
                            and 
                            (self.Larvae[i].Waste_ingested_total > 
                             self.Larvae[i].Waste_threshold)
                            ):
                                # ith larva has ingested too much waste
                                # assuming waste has an effect
                                # i.e., Conditions[1] == 1
                            if self.Larvae[i].Status != 2:
                                # If the ith larva is not post crit. mass,
                                # it dies of waste toxicity
                                # Its status is set to 'poisoned' i.e. -2
                                self.Larvae[i].Status = -2
                                # Its mass, SA and length are set to 0
                                self.Larvae[i].Mass = 0
                                self.Larvae[i].Larval_SA = 0
                                self.Larvae[i].Larval_length = 0
                                # The time of larval death is recorded
                                self.Mort_time[i] = t
                            
                            elif self.Larvae[i].Status==2:
                                # ith larva is in post critical mass stage
                                # it commits to wandering i.e. Status = 3
                                self.Larvae[i].Status = 3
                                # The time to wandering is recorded
                                self.Dev_time[i] = t
                        
                        if (self.Larvae[i].Status==1 and
                        self.Larvae[i].Mass>=self.Larvae[i].Min_crit_mass):
                            # Larval mass has just exceeded min. crit. mass
                            # Its Status is changed from 
                            #'PreCrit'(i.e. 1) to 'PostCrit' (i.e. 2)
                            self.Larvae[i].Status = 2
                            # Post critical mass feeding timer + 1 t
                            self.Larvae[i].Post_crit_timer += 1
                            # Post crit timer is recorded
                            self.Post_crit_counter[t, i] = (
                            self.Larvae[i].Post_crit_timer)
                            
                        elif self.Larvae[i].Status==2:
                            # Larva is already in post crit stage
                            # Post critical mass feeding timer + 1 t
                            self.Larvae[i].Post_crit_timer += 1
                            # Post crit timer is recorded
                            self.Post_crit_counter[t, i] = (
                            self.Larvae[i].Post_crit_timer)
                            
                            if (self.Larvae[i].Post_crit_timer == 
                                self.Larvae[i].Post_crit_limit 
                                or 
                                self.Larvae[i].Mass >=
                                self.Larvae[i].Max_mass):
                                # Post critical stage larva is >=
                                # Post critical mass feeding timer or 
                                # current larval mass >=
                                # max larval mass possible
                                # Larva commits to wandering i.e. Status = 3
                                self.Larvae[i].Status = 3
                                # The time to wandering is recorded
                                self.Dev_time[i] = t
                                                
                if t==(Time-1):
                    # At the final time step
                    if (0<=self.Larvae[i].Status<3):
                        # if the larva is still not out of culture
                        
                        # The ith larva has run out of time.
                        # it dies of culture timer running out
                        # Its status is set to 'culled' i.e. -5
                        # NOTE:
                        # This is a diagnostic step. When getting the final
                        # results, it is ensured that enough time steps 
                        # are used such that all larvae reach a
                        # natural conclusion, and are not culled.
                        self.Larvae[i].Status = -5
                        # Its mass, SA and length are set to 0
                        self.Larvae[i].Mass = 0
                        self.Larvae[i].Larval_SA = 0
                        self.Larvae[i].Larval_length = 0
                        # The time of larval death is recorded
                        self.Mort_time[i] = t
                    
                    # Records critical larval data for diagnostics
                    self.Mass_records[0, i] = self.Larvae[i].Egg_mass
                    self.Mass_records[1, i] = self.Larvae[i].Min_crit_mass
                    self.Mass_records[2, i] = self.Mass_profile[t-1, i]
                    self.Mass_records[3, i] = self.Mass_percentile[t, i]
                    self.Mass_records[4, i] = self.Larvae[i].Max_mass
                    self.Mass_records[5, i] = self.Larvae[i].Post_crit_timer
                    self.Mass_records[6, i] = self.Larvae[i].Status
                    
                # At the end of every time step, larval Mass, SA, length and
                # larval status are recorded for ith larva
                self.Mass_profile[t, i] = self.Larvae[i].Mass
                self.SA_profile[t, i] = self.Larvae[i].Larval_SA
                self.Length_profile[t, i] = self.Larvae[i].Larval_length
                self.Status_profile[t, i] = self.Larvae[i].Status
                    
            # Food profile updated with realised food mass
            self.Food_profile[t] = self.Food_current
            # Waste profile updated with realised waste
            self.Waste_profile[t] = Waste_current
            
            # Waste excretion timer reduces timer counter of prev. time steps
            self.Waste_new[self.Waste_new[:, 3] > -1, 3] -= 1
            # Current time step waste counter is set
            self.Waste_new[t, 3] = Excrete_timer
            
            # Find the time point from which waste is excreted at the current t
            W_excr_T = np.where(self.Waste_new[:, 3] == 0)
            # For debugging, ensures that there is only 1 or no value for 
            # time point of fresh waste excreted
            assert 0 <= len(W_excr_T[0]) <= 1
            
            # Waste to be deposited, placeholder = 0.
            Wdep = 0
            
            if len(W_excr_T[0]) == 1:
                # If there IS a time point found, 
                # from which waste will be excreted
                # Set W_excr_T as the waste time point
                W_excr_T = W_excr_T[0][0]
                # Calculate the waste excreted at W_excr_T
                Wdep = self.Waste_new[W_excr_T, 0]
            
            # Realised waste updated with fresh waste, for next time step
            Waste_current += Wdep
            
        # Egg to wandering survivorship is recorded
        # all the larvae that have >0 Dev. time are considered survivors
        self.Survivorship = ((self.Dev_time > 0).sum())/Larval_count
        
        return None
    
    #### End of Culture_run function #########################################
        
        
        
        
        